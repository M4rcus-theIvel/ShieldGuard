from __future__ import annotations

from typing import Dict, List, Tuple

from .utils import load_config, save_config

LANGUAGES: List[Tuple[str, str]] = [
    ("vi", "Tiếng Việt"),
    ("en", "English"),
    ("zh", "中文 (简体)"),
    ("es", "Español"),
    ("de", "Deutsch"),
]

LANG_CODE_TO_LABEL: Dict[str, str] = dict(LANGUAGES)
LANG_LABEL_TO_CODE: Dict[str, str] = {label: code for code, label in LANGUAGES}

_current_lang: str = "vi"


def init_language() -> str:
    global _current_lang
    cfg = load_config()
    code = str(cfg.get("language", "vi"))
    if code not in LANG_CODE_TO_LABEL:
        code = "vi"
    _current_lang = code
    return _current_lang


def get_lang() -> str:
    return _current_lang


def set_lang(code: str) -> str:
    global _current_lang
    if code not in LANG_CODE_TO_LABEL:
        code = "vi"
    _current_lang = code
    cfg = load_config()
    cfg["language"] = code
    save_config(cfg)
    return _current_lang


